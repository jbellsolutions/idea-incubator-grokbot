#!/usr/bin/env python3
"""One agent per role: write AGENTS.md and agents/<role>.md from MASTER-PROMPT.md and roles/.

    python3 tools/agents.py            write the files
    python3 tools/agents.py --check    exit 1 if they are missing or out of date

Each role is its own Grok bot (its own agent), on the same Grok account, so they share one computer, one
workspace and its sign-ins. agents/<role>.md is everything one agent needs: the name to give the bot, the one
line the owner pastes into it, and the memory block (the team's master prompt, then that role's own section).
Agents hand work to each other through files in requests/<role>/, never chat.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def block(text):
    m = re.search(r"```\n(.*?)\n```", text, re.S)
    return m.group(1) if m else ""


def team():
    m = re.search(r"You are on the (.+?) team", (ROOT / "MASTER-PROMPT.md").read_text())
    if m:
        return m.group(1).strip()
    m = re.search(r"^# Project charter: (.+)$", (ROOT / "CHARTER.md").read_text(), re.M)
    return m.group(1).strip() if m else ROOT.name


def workspace():
    m = re.search(r"Your workspace is (\S+?)/?\.", (ROOT / "MASTER-PROMPT.md").read_text())
    return (m.group(1) if m else "/workspace/" + ROOT.name).rstrip("/")


def roles():
    out = []
    for p in sorted((ROOT / "roles").glob("*.md")):
        if p.name.startswith("_"):
            continue
        t = p.read_text()
        sec = re.search(r"## System prompt section[^\n]*\n+```\n(.*?)\n```", t, re.S)
        job = re.search(r"## Job\n+(.+)", t)
        n = len(re.findall(r"^\| .+ \| `?[\d*/, -]+ [\d*/, -]+ [\d*/, -]+ [\d*/, -]+ [\d*/, A-Za-z-]+`? *\|", t, re.M))
        out.append({"role": p.stem, "section": sec.group(1) if sec else "", "job": job.group(1).strip() if job else "", "routines": n})
    return sorted(out, key=lambda r: (r["role"] != "lead", r["role"]))


def build():
    t, ws, master = team(), workspace(), block((ROOT / "MASTER-PROMPT.md").read_text())
    rs, files = roles(), {}
    rows = []
    for r in rs:
        name = f"{t} · {r['role']}"
        first = r["role"] == "lead"
        paste = (f"You are {name}, the lead agent of the {t} team. Follow HANDOFF.md, Part 2, from step 1." if first else
                 f"You are {name}, the {r['role']} agent of the {t} team. Read {ws}/repo/agents/{r['role']}.md and do what it says. "
                 f"Nothing sends, posts, spends or writes to a CRM until I say yes.")
        files[f"agents/{r['role']}.md"] = f"""# The {r['role']} agent

Generated by `python3 tools/agents.py` from MASTER-PROMPT.md and roles/{r['role']}.md. Change those, then run it again.

| | |
|---|---|
| Bot name | **{name}** |
| Its role | {r['job'] or r['role']} |
| Its routines | The `{r['role']}` rows in TRIGGER-MAP.md, created on this bot, switched off |
| Its charter | [../roles/{r['role']}.md](../roles/{r['role']}.md) |

## What the owner pastes into this bot

{"The pack's one link, from HANDOFF.md Part 1. The lead agent is the first bot made; it unpacks the pack for every agent." if first else "> " + paste}

## What this agent does first

1. Save the memory block below to memory, word for word.
2. Save `guards/SKILL.md` and every skill in `skills/{r['role']}/` as a private skill.
3. Create this role's routines from TRIGGER-MAP.md on this bot, each switched off, and add them to `{ws}/context/team-registry.md` with this bot's name.
4. Write one line to `{ws}/log/setup.md`: the bot's name, its role, the routines made.

## Memory block

```
You are {name}: the {r['role']} agent of the {t} team. Each role on this team is its own agent. You work only as {r['role']}. Work for another role goes to that agent as a file in requests/<role>/.

{master}

{r['section']}
```
"""
        rows.append(f"| {r['role']} | **{name}** | {r['job'] or ''} | [agents/{r['role']}.md](agents/{r['role']}.md) |")
    files["AGENTS.md"] = f"""# {t}: one agent per role

Generated by `python3 tools/agents.py`. Each role is its own Grok bot, its own agent. They are all on the same Grok account, so they share one computer, one workspace (`{ws}/`) and its sign-ins. The lead agent plans the day, keeps the scoreboard and holds the one queue for the owner. Agents hand work to each other through files in `requests/<role>/`.

| Role | The bot to make | Job | Its page |
|---|---|---|---|
""" + "\n".join(rows) + f"""

## Setting the team up

1. Make the lead bot and paste the pack's one link into it (HANDOFF.md, Part 1). It unpacks the pack into `{ws}/repo/` and builds the workspace.
2. For each other role, make one bot with the name above and paste the line on its page. It reads its own page from the shared workspace and sets itself up.
3. Every routine is made on its own role's bot, switched off.

{len(rs)} agents. A bot holds 50 routines, so each agent has its own 50.
"""
    return files


def main(a):
    files = build()
    if "--check" in a:
        bad = [f for f, c in files.items() if not (ROOT / f).exists() or (ROOT / f).read_text() != c]
        print("agents: ok" if not bad else "agents: out of date: " + ", ".join(bad) + " (run python3 tools/agents.py)")
        return 1 if bad else 0
    (ROOT / "agents").mkdir(exist_ok=True)
    keep = set(files)
    for old in (ROOT / "agents").glob("*.md"):
        if f"agents/{old.name}" not in keep:
            old.unlink()
    for f, c in files.items():
        (ROOT / f).write_text(c)
    print(f"wrote AGENTS.md and {len(files) - 1} agent pages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
